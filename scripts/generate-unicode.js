// Generate the small character-class tables used by the external inline scanner.
// Pin the Unicode data version independently of the host's locale and C library.
const fs = require('node:fs');
const path = require('node:path');

const UNICODE_VERSION = '17.0';
if (process.versions.unicode !== UNICODE_VERSION) {
  throw new Error(
    `Unicode ${UNICODE_VERSION} data required; this Node has ${process.versions.unicode}`,
  );
}

function rangesFor(pattern) {
  const ranges = [];
  for (let point = 0; point <= 0x10ffff; point++) {
    if (!pattern.test(String.fromCodePoint(point))) continue;
    const last = ranges.at(-1);
    if (last && last[1] === point - 1) last[1] = point;
    else ranges.push([point, point]);
  }
  return ranges;
}

const table = (name, ranges) =>
  `static const uint32_t ${name}[][2] = {\n${ranges
    .map(
      ([first, last]) =>
        `    {0x${first.toString(16)}, 0x${last.toString(16)}},`,
    )
    .join('\n')}\n};\n`;

const output = `// Generated by scripts/generate-unicode.js from Unicode ${UNICODE_VERSION} General_Category.
// Source: Node.js RegExp property tables (ICU); see THIRD_PARTY_NOTICES.
#ifndef TREE_SITTER_MARKDOWN_UNICODE_H_
#define TREE_SITTER_MARKDOWN_UNICODE_H_

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

${table('UNICODE_PUNCTUATION', rangesFor(/\p{P}/u))}
${table('UNICODE_SPACES', rangesFor(/\p{Zs}/u))}
static bool unicode_range_contains(int32_t character, const uint32_t ranges[][2], size_t count) {
    if (character < 0) return false;
    uint32_t point = (uint32_t)character;
    size_t left = 0;
    size_t right = count;
    while (left < right) {
        size_t middle = left + (right - left) / 2;
        if (point < ranges[middle][0]) right = middle;
        else if (point > ranges[middle][1]) left = middle + 1;
        else return true;
    }
    return false;
}

// CommonMark punctuation includes ASCII punctuation even when Unicode calls
// that character a symbol (for example '$', '+', '<', '=' and '>').
static bool is_unicode_punctuation(int32_t character) {
    return (character >= '!' && character <= '/') ||
           (character >= ':' && character <= '@') ||
           (character >= '[' && character <= 0x60) ||
           (character >= '{' && character <= '~') ||
           unicode_range_contains(character, UNICODE_PUNCTUATION,
               sizeof(UNICODE_PUNCTUATION) / sizeof(UNICODE_PUNCTUATION[0]));
}

static bool is_unicode_whitespace(int32_t character) {
    return character == '\\t' || character == '\\n' || character == '\\f' || character == '\\r' ||
           unicode_range_contains(character, UNICODE_SPACES,
               sizeof(UNICODE_SPACES) / sizeof(UNICODE_SPACES[0]));
}

#endif
`;

const destination = path.join(
  __dirname,
  '..',
  'tree-sitter-markdown-inline',
  'src',
  'unicode.h',
);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8') !== output)
    throw new Error('Unicode tables are stale');
} else {
  fs.writeFileSync(destination, output);
}
